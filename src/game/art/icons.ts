/** run-length rows of an icon: [row, x0, length] — merged so one icon costs a handful of quads */
export interface IconRuns { w: number; h: number; runs: number[] }
const cache: Record<string, IconRuns> = {};
export function iconRuns(name: string): IconRuns {
  let c = cache[name];
  if (c) return c;
  const rows = ICONS[name] ?? ICONS.star;
  const w = Math.max(...rows.map((r) => r.length)), h = rows.length, runs: number[] = [];
  for (let y = 0; y < h; y++) {
    let x = 0;
    const r = rows[y].padEnd(w, ".");
    while (x < w) {
      if (r[x] !== "#") {
        x++;
        continue;
      }
      let e = x;
      while (e < w && r[e] === "#") e++;
      runs.push(y, x, e - x);
      x = e;
    }
  }
  c = cache[name] = { w, h, runs };
  return c;
}

